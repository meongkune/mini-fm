STARTERS = {"GK": 1, "DF": 4, "MF": 4, "FW": 2}
BIAS = {"GK": (-30, 8), "DF": (-12, 7), "MF": (0, 0), "FW": (8, -22)}  # 포지션별 (공격, 수비) 성향


def clamp(v):
    return max(40, min(95, v))


teams = []
for code, name, short, color, alt, base, squad in TEAMS:
    players = []
    numbers = iter(rng.sample(range(2, 50), 18))
    for pos in ("GK", "DF", "MF", "FW"):
        for i, pname in enumerate(squad[pos]):
            b = base + (3 if i < STARTERS[pos] else -4)  # 주전급과 후보급 차이
            players.append({
                "id": f"{code}{len(players) + 1:02d}",
                "name": pname,
                "pos": pos,
                "number": 1 if (pos == "GK" and i == 0) else next(numbers),
                "age": rng.randint(19, 33),
                "att": clamp(b + BIAS[pos][0] + rng.randint(-6, 6)),
                "def": clamp(b + BIAS[pos][1] + rng.randint(-6, 6)),
                "sta": clamp(b + rng.randint(-9, 9)),
            })
    assert len(players) == 18, code
    teams.append({"id": code, "name": name, "short": short, "color": color, "alt": alt, "players": players})

